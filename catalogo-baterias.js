function todasLasBateriasWR(){
  return Object.values(catalogoBateriasWR).flat();
}

function normalizarCodigoBateriaWR(texto){
  return String(texto || "").toUpperCase().replace(/[\s_]+/g, "").replace(/-/g, "");
}

function buscarFichaBateriaWR(texto){
  const t=normalizarCodigoBateriaWR(texto);
  return todasLasBateriasWR().find(b=>{
    const m=normalizarCodigoBateriaWR(b.modelo);
    return t===m || t.includes(m) || m.includes(t);
  }) || null;
}

function buscarFamiliaBateriaWR(texto){
  const t=normalizarCodigoBateriaWR(texto);
  if(/R42L|R42O|GN42L|42MF|42HD|42FHD/.test(t)) return "42 / 42R";
  if(/RN70|NS70|27800|N70/.test(t)) return "N-70";
  if(/RN50|N50|24L800/.test(t)) return "N-50";
  if(/NS60/.test(t)) return "N-60";
  if(/NS40/.test(t)) return "N-40";
  return null;
}

function fichaBateriaHTMLWR(b){
  const filas=[];
  filas.push(`<strong>🔋 ${b.modelo}</strong>`);
  filas.push(`Marca: <strong>${b.marca}</strong>`);
  filas.push(`Categoría: <strong>${b.categoria}</strong>`);
  filas.push(`Tipo: <strong>${b.tipo}</strong>`);
  if(b.grupoJIS) filas.push(`Grupo/familia: <strong>${b.grupoJIS}</strong>`);
  if(b.voltaje) filas.push(`Voltaje: <strong>${b.voltaje}V</strong>`);
  if(b.capacidadAh) filas.push(`Capacidad: <strong>${b.capacidadAh} Ah (20HR)</strong>`);
  if(b.cca) filas.push(`CCA: <strong>${b.cca} A</strong>`);
  if(b.rc) filas.push(`RC: <strong>${b.rc} min</strong>`);
  if(b.arranqueLabel) filas.push(`Arranque indicado en etiqueta: <strong>${b.arranqueLabel}</strong>`);
  if(b.dimensiones) filas.push(`Dimensiones: <strong>${b.dimensiones}</strong>`);
  if(b.pais) filas.push(`Fabricación: <strong>${b.pais}</strong>`);
  if(b.garantiaCasa) filas.push(`Garantía en Casa de las Baterías: <strong>${b.garantiaCasa}</strong>`);
  filas.push(`<span style="font-size:12px;color:#666">El grupo de garantía no se interpreta como grupo BCI.</span>`);
  return "🔎 Ficha verificada:"+"<br><br>"+filas.join("<br>")+"<br><br><span style=\"font-size:12px;color:#666\">Fuente: "+b.fuente+". La equivalencia final debe comprobar polaridad, bornes, medidas y especificación del vehículo.</span>";
}

